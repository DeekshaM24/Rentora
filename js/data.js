window.escapeRentoraHtml = (value) => String(value ?? "").replace(/[&<>"']/g, (character) => ({
  "&": "&amp;",
  "<": "&lt;",
  ">": "&gt;",
  '"': "&quot;",
  "'": "&#39;"
})[character]);

window.RENTORA_OWNER_LISTINGS_KEY = "rentora:owner-listings";
window.readRentoraOwnerListings = () => {
  try {
    const listings = JSON.parse(localStorage.getItem(window.RENTORA_OWNER_LISTINGS_KEY) || "[]");
    return Array.isArray(listings) ? listings : [];
  } catch {
    return [];
  }
};
window.writeRentoraOwnerListings = (listings) => {
  try {
    localStorage.setItem(window.RENTORA_OWNER_LISTINGS_KEY, JSON.stringify(listings));
    return true;
  } catch {
    return false;
  }
};
window.getRentoraProperties = ({ includeInactive = false } = {}) => {
  const ownerListings = window.readRentoraOwnerListings().filter((listing) => includeInactive || listing.status === "active");
  return [...window.RENTORA_PROPERTIES, ...ownerListings];
};